//! hsm-finishes reads or refreshes the viewer's material finishes from the authored catalogs.
use anyhow::{Context, Result, bail, ensure};
use hsm_shared_data::color;
use serde_json::{Value, json};
use std::path::{Path, PathBuf};

const MATERIALS: &str = "tools/hsm/shared-data/catalog/materials.json";
const ROUTING: &str = "tools/hsm/shared-data/catalog/routing.json";
const TABLE: &str = "web/public/finishes.json";
const CONTRACT: &str = "web/contracts/material-finishes.js";
const EXPORT: &str = "export const PETGF_BLACK = ";

struct Finishes {
    table: Value,
    petgf: Value,
}

fn read(path: &Path) -> Result<Value> {
    serde_json::from_slice(
        &std::fs::read(path).with_context(|| format!("reading {}", path.display()))?,
    )
    .with_context(|| format!("parsing {}", path.display()))
}

fn finishes(root: &Path) -> Result<Finishes> {
    let catalog = color::material_catalog(&read(&root.join(MATERIALS))?)?;
    let rows = color::catalog_finishes(&catalog, &read(&root.join(ROUTING))?)?;
    let black = color::dispatch(
        "linear",
        &json!({"color": {"args": catalog["colors"]["M_PETGF_BLACK"]}}),
    )?;
    let petgf = rows
        .iter()
        .find(|row| row["rgb"] == black)
        .context("the finish table contains no PET-GF black")?
        .clone();
    Ok(Finishes {
        table: json!({"finishes": rows}),
        petgf,
    })
}

fn same(a: &Value, b: &Value) -> bool {
    match (a, b) {
        (Value::Number(a), Value::Number(b)) => match (a.as_f64(), b.as_f64()) {
            (Some(a), Some(b)) => (a - b).abs() <= 1e-12,
            _ => a == b,
        },
        (Value::Array(a), Value::Array(b)) => {
            a.len() == b.len() && a.iter().zip(b).all(|(a, b)| same(a, b))
        }
        (Value::Object(a), Value::Object(b)) => {
            a.len() == b.len()
                && a.iter()
                    .all(|(key, a)| b.get(key).is_some_and(|b| same(a, b)))
        }
        _ => a == b,
    }
}

fn contract_value(text: &str) -> Result<Value> {
    let (_, value) = text
        .split_once(EXPORT)
        .context("the PET-GF contract exports no material finish")?;
    serde_json::from_str(
        value
            .trim()
            .strip_suffix(';')
            .context("the PET-GF contract has no export terminator")?,
    )
    .context("parsing the PET-GF material contract")
}

fn check(root: &Path, data: &Finishes) -> Result<()> {
    ensure!(
        same(&read(&root.join(TABLE))?, &data.table),
        "{TABLE} differs from the authored catalogs; run hsm-finishes --write"
    );
    let contract = std::fs::read_to_string(root.join(CONTRACT))
        .context("reading the PET-GF material contract")?;
    ensure!(
        same(&contract_value(&contract)?, &data.petgf),
        "{CONTRACT} differs from the authored catalog; run hsm-finishes --write"
    );
    Ok(())
}

fn write(root: &Path, data: &Finishes) -> Result<()> {
    let rows = data.table["finishes"]
        .as_array()
        .context("material finish rows")?;
    let body = rows
        .iter()
        .map(serde_json::to_string)
        .collect::<std::result::Result<Vec<_>, _>>()?
        .join(",\n  ");
    let table = format!("{{\n \"finishes\": [\n  {body}\n ]\n}}\n");
    let contract = format!(
        "// Generated by hsm-finishes from the material catalog.\n{EXPORT}{};\n",
        serde_json::to_string(&data.petgf)?
    );
    for (path, text) in [(TABLE, table), (CONTRACT, contract)] {
        let path = root.join(path);
        std::fs::create_dir_all(path.parent().context("the finish output's directory")?)?;
        std::fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
    }
    Ok(())
}

fn main() -> Result<()> {
    let mut root = PathBuf::from(".");
    let mut mode = "read";
    let mut selected = false;
    let mut args = std::env::args().skip(1);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--root" => {
                root = args
                    .next()
                    .map(PathBuf::from)
                    .context("--root needs a checkout path")?
            }
            "--read" | "--check" | "--write" => {
                ensure!(!selected, "choose only one of --read, --check and --write");
                selected = true;
                mode = match arg.as_str() {
                    "--check" => "check",
                    "--write" => "write",
                    _ => "read",
                };
            }
            "-h" | "--help" => {
                println!(
                    "hsm-finishes [--root PATH] [--read | --check | --write]\n\nReads the material and tube-stock catalogs and prints the viewer finish table by default.\n--check compares the saved viewer table and PET-GF contract without writing.\n--write refreshes both saved files. This command is outside the normal build.\n\nInputs: {MATERIALS}, {ROUTING}\nOutputs: {TABLE}, {CONTRACT}"
                );
                return Ok(());
            }
            _ => bail!("unknown hsm-finishes argument {arg}; use --help"),
        }
    }
    let data = finishes(&root)?;
    match mode {
        "check" => {
            check(&root, &data)?;
            println!("material finishes match the authored catalogs");
        }
        "write" => {
            write(&root, &data)?;
            println!("wrote {TABLE} and {CONTRACT}");
        }
        _ => println!("{}", serde_json::to_string_pretty(&data.table)?),
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn authored_catalogs_match_the_saved_viewer_and_petgf_contract() -> Result<()> {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..");
        check(&root, &finishes(&root)?)
    }

    #[test]
    fn material_edits_reach_the_shared_chip_palette() -> Result<()> {
        let mut input: Value = serde_json::from_str(include_str!("../catalog/materials.json"))?;
        let routing = serde_json::from_str(include_str!("../catalog/routing.json"))?;
        input["colors"]["M_PETGF_BLACK"]["args"] = json!([0.18, 0.19, 0.22]);
        let catalog = color::material_catalog(&input)?;
        let rows = color::catalog_finishes(&catalog, &routing)?;
        let black = color::dispatch(
            "linear",
            &json!({"color": {"args": catalog["colors"]["M_PETGF_BLACK"]}}),
        )?;
        assert!(rows.iter().any(|row| row["rgb"] == black));
        Ok(())
    }
}
