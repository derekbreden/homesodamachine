//! Firmware preparation stamps source identity and prepares the display's flash assets.
use crate::{execute, option, text_output, validate_args, write_changed};
use anyhow::{Context, Result, bail, ensure};
use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
    time::SystemTime,
};

pub fn pre_build(root: &Path, args: &[String]) -> Result<()> {
    ensure!(
        validate_args(args, &[], &["--environment", "--build-dir"])?.is_empty(),
        "firmware-pre-build --environment ENV --build-dir PATH"
    );
    let environment = option(args, "--environment")?.context("--environment is required")?;
    let build = PathBuf::from(option(args, "--build-dir")?.context("--build-dir is required")?);
    let source = match environment.as_str() {
        "appliance" => "firmware/src_appliance",
        "esp32s3_faucet" => "firmware/src_faucet",
        "esp32s3_front" => "firmware/src_front",
        "pcba_bench" => "firmware/src_pcba_bench",
        _ => bail!("unknown firmware environment {environment}"),
    };
    let today = text_output(Command::new("date").arg("+%Y.%m.%d"))?;
    let git = |args: &[&str]| text_output(Command::new("git").current_dir(root).args(args));
    let version = match git(&["rev-parse", "--short", "HEAD"]) {
        Ok(mut revision) => {
            let date = git(&[
                "show",
                "-s",
                "--format=%cd",
                "--date=format:%Y.%m.%d",
                "HEAD",
            ])
            .unwrap_or_else(|_| today.clone());
            if git(&["status", "--porcelain"]).is_ok_and(|v| !v.is_empty()) {
                revision.push('+');
            }
            format!("{date} {revision}")
        }
        Err(_) => format!("{today} unknown"),
    };
    let epoch = git(&["show", "-s", "--format=%ct", "HEAD"])
        .ok()
        .and_then(|v| v.parse::<u64>().ok())
        .unwrap_or(0);
    write_changed(&root.join(source).join("fw_version.h"), format!("// Auto-generated by hsm-peripheral firmware-pre-build\n#define FW_VERSION \"{version}\"\n#define FW_BUILD_EPOCH {epoch}u\n").as_bytes())?;
    let build_time = root.join(source).join("fw_build_time.h");
    if wants_build_time(&root.join(source))? {
        let timestamp = text_output(Command::new("date").arg("+%b %d %Y %H:%M:%S"))?;
        write_changed(&build_time, format!("// Auto-generated by hsm-peripheral firmware-pre-build\n#define FW_BUILD_TIME \"{timestamp}\"\n").as_bytes())?;
    } else if build_time.is_file() {
        fs::remove_file(&build_time)?;
    }

    let library = root
        .join(".pio/libdeps")
        .join(&environment)
        .join("Tiny Protocol/src");
    if library.is_dir() {
        for name in ["TinyProtocol.cpp", "link/TinySerialFdLink.cpp"] {
            let path = library.join(name);
            if path.is_file() {
                fs::remove_file(path)?;
            }
        }
        let path = library.join("TinyProtocolFd.cpp");
        if path.is_file() {
            let original = fs::read_to_string(&path)?;
            let patched = original
                .replace("init.retry_timeout = 200;", "init.retry_timeout = 2000;")
                .replace("init.retries = 2;", "init.retries = 4;");
            if original != patched {
                fs::write(path, patched)?;
            }
        }
    }
    let marketing = env::var_os("HSM_MARKETING_BIN").unwrap_or_else(|| "hsm-marketing".into());
    if matches!(environment.as_str(), "esp32s3_front" | "esp32s3_faucet") {
        let logos = build.join("logos.bin");
        let newest = newest_image(&root.join("firmware/src_front/images"), |s| {
            s.starts_with("flavor")
        })?;
        if outdated(&logos, newest) {
            if let Some(parent) = logos.parent() {
                fs::create_dir_all(parent)?;
            }
            execute(
                Command::new(&marketing)
                    .current_dir(root)
                    .args(["make-logos", "-o"])
                    .arg(&logos)
                    .arg("-q"),
            )?;
        }
    }
    if environment == "esp32s3_front" {
        let art = build.join("art.bin");
        let newest = newest_image(&root.join(source).join("images"), |s| s.ends_with(".h"))?;
        if outdated(&art, newest) {
            if let Some(parent) = art.parent() {
                fs::create_dir_all(parent)?;
            }
            execute(
                Command::new(&marketing)
                    .current_dir(root)
                    .args(["make-art", "enclosure", "-o"])
                    .arg(&art)
                    .arg("-q"),
            )?;
        }
    }
    Ok(())
}

fn wants_build_time(directory: &Path) -> Result<bool> {
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            if wants_build_time(&path)? {
                return Ok(true);
            }
        } else if path.file_name().is_some_and(|v| v != "fw_build_time.h")
            && matches!(
                path.extension().and_then(|v| v.to_str()),
                Some("cpp" | "h" | "c")
            )
            && String::from_utf8_lossy(&fs::read(path)?).contains("fw_build_time.h")
        {
            return Ok(true);
        }
    }
    Ok(false)
}

fn newest_image(directory: &Path, accepts: impl Fn(&str) -> bool) -> Result<SystemTime> {
    let mut newest = SystemTime::UNIX_EPOCH;
    for entry in fs::read_dir(directory)? {
        let entry = entry?;
        if accepts(&entry.file_name().to_string_lossy()) {
            newest = newest.max(entry.metadata()?.modified()?);
        }
    }
    Ok(newest)
}

fn outdated(path: &Path, newest: SystemTime) -> bool {
    fs::metadata(path)
        .and_then(|v| v.modified())
        .map_or(true, |v| v < newest)
}
