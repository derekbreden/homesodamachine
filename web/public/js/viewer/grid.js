// STEP thumbnails are server-rendered PNGs committed next to each part and
// served at /thumbs/<file>.png (generated by the part's own export — see
// hardware/scripts/_cadq_export.py + tools/render/render-thumbnails.js). The grid
// just downloads the image; no per-card occt parse / WebGL render anymore.
// paintStepThumb wires the <img>'s error fallback to a client render BEFORE
// setting src, so a STEP with no committed thumbnail yet (e.g. an imported
// reference part, or one not regenerated since this landed) still shows
// something instead of a broken image. `bust` forces past the browser cache
// after a live regen.
export function paintStepThumb(card, { bust = false } = {}) {
  const img = card.querySelector("img");
  if (!img) return;
  const file = card.dataset.file;
  img.onerror = () => {
    img.onerror = null;
    renderThumbnail(file).then((url) => { if (url) img.src = url; });
  };
  img.src = `/thumbs/${file}.png${bust ? `?t=${Date.now()}` : ""}`;
}

function shortName(file, ext = ".step") {
  const parts = file.split("/");
  const name = parts.pop().replace(ext, "");
  const dir = parts.join("/");
  return { name, dir };
}

// Subsystem grouping for the Prints and Cuts grids. Files under
// printed-parts/<subsystem>/... or cut-parts/<subsystem>/... bucket by
// <subsystem>; anything else buckets by its top-level path segment
// (e.g. reference/ STEPs land in their own group). Categories sort
// alphabetically. Within a group the card's `dir` label drops the
// redundant subsystem prefix so the leaf folder reads cleanly under
// the subheader.
function categoryAndPartPath(file) {
  const parts = file.split("/");
  const filename = parts.pop();
  let category, partPath;
  if ((parts[0] === "printed-parts" || parts[0] === "cut-parts") && parts.length > 1) {
    category = parts[1];
    partPath = parts.slice(2).join("/");
  } else {
    category = parts[0] || "";
    partPath = parts.slice(1).join("/");
  }
  return { category, partPath, filename };
}

function titleCaseCategory(s) {
  return s.replace(/[-_]/g, " ")
    .split(" ")
    .map((w) => (w ? w.charAt(0).toUpperCase() + w.slice(1) : ""))
    .join(" ");
}

function groupFilesByCategory(files) {
  const groups = new Map();
  for (const f of files) {
    const { category } = categoryAndPartPath(f);
    if (!groups.has(category)) groups.set(category, []);
    groups.get(category).push(f);
  }
  return new Map([...groups.entries()].sort(([a], [b]) => a.localeCompare(b)));
}

// Append a sequence of [subsection-header, card, card, ...] groups to
// gridEl, one group per category returned by groupFilesByCategory.
// Caller supplies the thumbnail markup (it differs between STEP/DXF
// "loading..." placeholders and the wrapped mmd-thumb structure) plus
// the click handler.
function renderGroupedCards({ files, ext, type, thumbnailHtml, onClick }) {
  for (const [category, group] of groupFilesByCategory(files)) {
    const sub = document.createElement("div");
    sub.className = "subsection-header";
    sub.textContent = titleCaseCategory(category);
    state.gridEl.appendChild(sub);
    for (const file of group) {
      const { partPath, filename } = categoryAndPartPath(file);
      const name = filename.replace(ext, "");
      const card = document.createElement("div");
      card.className = "card";
      card.dataset.file = file;
      card.dataset.type = type;
      card.innerHTML = `${thumbnailHtml(file)}<div class="label"><span class="dir">${partPath}</span>${name}</div>`;
      card.addEventListener("click", () => onClick(file));
      state.gridEl.appendChild(card);
    }
  }
}

// Assembly cards — the printable 4×6 deck (hardware/assembly/cards). Arrives
// deck-ordered from /api/cards with each card's own printed identity, so the
// grid groups by subsystem in arrival order rather than re-deriving the build
// sequence. The subheader takes the subsystem's own accent colour, which is the
// same colour the card prints its code chip in — a scan down the page reads as
// the deck reads.
//
// The thumbnail is the card itself in a scaled iframe, mounted lazily by the
// observer at the bottom of buildGrid. There is no separate thumbnail artifact:
// the card you see in the grid is the file that goes to the printer.
//
// Cards get their own nested grid rather than sharing the page's track sizing.
// The page tracks are sized for part thumbnails; a card scaled into one is a
// coloured smudge you have to open to identify. Its own grid can ask for the
// width a card needs to stay readable in place, and packs cleanly instead of
// stranding a spare track at the end of every row.
function buildCardSection() {
  const header = document.createElement("div");
  header.className = "section-header";
  header.textContent = "Assembly cards";
  state.gridEl.appendChild(header);

  if (!state.cards || state.cards.length === 0) {
    const empty = document.createElement("div");
    empty.className = "empty-state";
    empty.textContent = "No cards yet.";
    state.gridEl.appendChild(empty);
    return;
  }

  const deck = document.createElement("div");
  deck.className = "deck-grid";
  state.gridEl.appendChild(deck);

  let group = null;
  for (const card of state.cards) {
    if (card.subsystemLabel !== group) {
      group = card.subsystemLabel;
      const sub = document.createElement("div");
      sub.className = "subsection-header deck-header";
      sub.textContent = group;
      if (card.accent) sub.style.color = card.accent;
      deck.appendChild(sub);
    }
    const el = document.createElement("div");
    el.className = "card card-deck";
    el.dataset.file = card.path;
    el.dataset.type = "card";
    const code = card.code ? `<span class="dir">${card.code}</span>` : "";
    el.innerHTML = `<div class="card-thumb" data-file="${card.path}"><div class="placeholder">loading...</div></div>` +
      `<div class="label">${code}${card.title}</div>`;
    if (card.accent) el.style.setProperty("--card-accent", card.accent);
    el.addEventListener("click", () => openCardDetail(card.path));
    deck.appendChild(el);
  }
}

// One viewer page area at a time. The path determines which section the
// grid renders.
export function currentSection() {
  const tail = location.pathname.replace(/\/$/, "");
  if (tail === "/charts") return "charts";
  if (tail === "/drawings") return "drawings";
  if (tail === "/pcb") return "pcb";
  return "parts";
}

export function buildGrid() {
  state.gridEl.innerHTML = "";
  const section = currentSection();

  if (section === "parts") {
    // Two subsections: Prints (STEP, 3D-printable) then Cuts (DXF, laser-
    // cut sheet). Within each, cards are further grouped under subsystem
    // subheaders (Cold Core, Flavor, Faucet, ...) derived from the folder
    // structure in hardware/printed-parts/ and hardware/cut-parts/. The
    // section headers always render so the structure is explicit even
    // when a subsection is empty; the empty-state replaces the would-be
    // card grid for that subsection.
    // STEP cards get a bare <img>; paintStepThumb sets its src (and error
    // fallback) after the cards mount. DXF cards still render client-side, so
    // they keep the "loading..." placeholder the dxf observer fills in.
    const stepThumb = (file) => `<img loading="lazy" alt="">`;
    const placeholderThumb = (file) => `<div class="placeholder" data-file="${file}">loading...</div>`;

    const printsHeader = document.createElement("div");
    printsHeader.className = "section-header";
    printsHeader.textContent = "Prints";
    state.gridEl.appendChild(printsHeader);
    if (state.allFiles.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty-state";
      empty.textContent = "No prints yet.";
      state.gridEl.appendChild(empty);
    } else {
      renderGroupedCards({ files: state.allFiles, ext: ".step", type: "step", thumbnailHtml: stepThumb, onClick: openDetail });
    }

    const cutsHeader = document.createElement("div");
    cutsHeader.className = "section-header";
    cutsHeader.textContent = "Cuts";
    state.gridEl.appendChild(cutsHeader);
    if (state.dxfFiles.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty-state";
      empty.textContent = "No cuts yet.";
      state.gridEl.appendChild(empty);
    } else {
      renderGroupedCards({ files: state.dxfFiles, ext: ".dxf", type: "dxf", thumbnailHtml: placeholderThumb, onClick: openDxfDetail });
    }

    // Assemblies (GLB): full-board 3D models, board body + placed components.
    const asmHeader = document.createElement("div");
    asmHeader.className = "section-header";
    asmHeader.textContent = "Assemblies";
    state.gridEl.appendChild(asmHeader);
    if (state.glbFiles.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty-state";
      empty.textContent = "No assemblies yet.";
      state.gridEl.appendChild(empty);
    } else {
      renderGroupedCards({ files: state.glbFiles, ext: ".glb", type: "glb", thumbnailHtml: placeholderThumb, onClick: openGlbDetail });
    }
  }

  if (section === "charts") {
    // Same subsystem grouping as Prints/Cuts, applied to mermaid files.
    // Charts live in hardware/topology/ and hardware/wiring/ rather than
    // under printed-parts/cut-parts, so categoryAndPartPath buckets them
    // by their top-level segment ("topology", "wiring", ...).
    const mmdThumb = (file) => `<div class="mmd-thumb" data-file="${file}"><div class="placeholder">loading...</div></div>`;
    if (state.mmdFiles.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty-state";
      empty.textContent = "No charts yet.";
      state.gridEl.appendChild(empty);
    } else {
      renderGroupedCards({ files: state.mmdFiles, ext: ".mmd", type: "mmd", thumbnailHtml: mmdThumb, onClick: openMmdDetail });
    }
  }

  if (section === "drawings") {
    // Two top-level sections, in order:
    //   Prints & Guides — customer-facing print artifacts (quick-start
    //     sheets and similar). Files live in
    //     `<root>/drawings/prints-and-guides/*.svg` and render as single
    //     cards; no per-part subsystem grouping, since these aren't
    //     per-part technical drawings. The SVG is the on-site display
    //     artifact; a sibling .pdf carries the print version.
    //   Line art — visible outlines only, the marketing/communication
    //     view of individual parts. Files live in
    //     `<part>/drawings/line-art/*.svg` and bucket by subsystem
    //     (Cold Core, Faucet, Enclosure, ...) via categoryAndPartPath.
    // The section headers always render so the structure is explicit even
    // when a section is empty.
    const drawingThumb = (file) => `<div class="drawing-thumb" data-file="${file}"><div class="placeholder">loading...</div></div>`;
    const printsFiles = state.drawingFiles.filter((f) => f.split("/").includes("prints-and-guides"));
    const lineArtFiles = state.drawingFiles.filter((f) => f.split("/").includes("line-art"));

    // Prints & Guides — render first. Cards are flat (no subsystem
    // sub-grouping); the label is just the filename minus extension.
    const printsHeader = document.createElement("div");
    printsHeader.className = "section-header";
    printsHeader.textContent = "Prints & Guides";
    state.gridEl.appendChild(printsHeader);
    if (printsFiles.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty-state";
      empty.textContent = "No prints yet.";
      state.gridEl.appendChild(empty);
    } else {
      for (const file of printsFiles) {
        const parts = file.split("/");
        const name = parts[parts.length - 1].replace(".svg", "");
        const card = document.createElement("div");
        card.className = "card";
        card.dataset.file = file;
        card.dataset.type = "drawing";
        card.innerHTML = `${drawingThumb(file)}<div class="label">${name}</div>`;
        card.addEventListener("click", () => openDrawingDetail(file));
        state.gridEl.appendChild(card);
      }
    }

    const lineArtHeader = document.createElement("div");
    lineArtHeader.className = "section-header";
    lineArtHeader.textContent = "Line art";
    state.gridEl.appendChild(lineArtHeader);
    if (lineArtFiles.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty-state";
      empty.textContent = "No line art yet.";
      state.gridEl.appendChild(empty);
    } else {
      renderGroupedCards({ files: lineArtFiles, ext: ".svg", type: "drawing", thumbnailHtml: drawingThumb, onClick: openDrawingDetail });
    }

    buildCardSection();
  }

  if (section === "pcb") {
    // PCB boards: one card per board, thumbnail is the Top copper view. The
    // card opens a modal with the Top / Bottom / Overlay toggle (pcb.js). The
    // dir subline carries the board's folder (minus the leading pcb/).
    const pcbThumb = (source) => `<div class="pcb-thumb" data-file="${source}"><div class="placeholder">loading...</div></div>`;
    const header = document.createElement("div");
    header.className = "section-header";
    header.textContent = "Boards";
    state.gridEl.appendChild(header);
    if (!state.pcbBoards || state.pcbBoards.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty-state";
      empty.textContent = "No boards yet.";
      state.gridEl.appendChild(empty);
    } else {
      for (const board of state.pcbBoards) {
        const dirLabel = board.dir.replace(/^pcb\//, "");
        const card = document.createElement("div");
        card.className = "card";
        card.dataset.file = board.source;
        card.dataset.type = "pcb";
        card.innerHTML = `${pcbThumb(board.source)}<div class="label"><span class="dir">${dirLabel}</span>${board.name}</div>`;
        card.addEventListener("click", () => openPcbDetail(board.source));
        state.gridEl.appendChild(card);
      }
    }
  }

  // Windowed thumbnail content. Every kind mounts as it nears the viewport and
  // releases once it's well past — see lazy.js for why this windows content
  // rather than rows, and for the measurements that motivated it. Each kind
  // supplies only what "mount" and "release" mean for its own thumbnail; the
  // scroll bookkeeping is shared.
  //
  // The handle is kept on `state` so the next buildGrid disconnects these
  // observers before the cards they watch are thrown away.
  state.gridWindow?.disconnect();

  const kinds = {
    // STEP: the committed server-rendered PNG (with a client-render fallback).
    // Releasing drops the src, which is what frees the decoded bitmap —
    // loading="lazy" defers the fetch but never gives the pixels back, and at
    // 400 x 400 x 4B each they are the whole cost of this page. The re-fetch on
    // return is a cache hit.
    step: {
      mount: (card) => paintStepThumb(card),
      unmount: (card) => {
        const img = card.querySelector("img");
        if (!img) return;
        // Drop the error handler first: it's what falls back to a client
        // render, and releasing the src must not look like a failed load.
        img.onerror = null;
        img.removeAttribute("src");
      },
    },
    dxf: imageThumb(renderDxfThumbnail),
    glb: imageThumb(renderGlbThumbnail),
    mmd: markupThumb({ hostSelector: ".mmd-thumb", render: renderMmdThumbnail }),
    drawing: markupThumb({ hostSelector: ".drawing-thumb", render: renderDrawingThumbnail }),
    pcb: markupThumb({ hostSelector: ".pcb-thumb", render: renderPcbThumbnail }),
    // Assembly cards: a mounted card is a live document, so this is the kind
    // where releasing matters most.
    card: {
      mount: (card) => mountCardThumbnail(card.querySelector(".card-thumb"), card.dataset.file),
      unmount: (card) => unmountCardThumbnail(card.querySelector(".card-thumb")),
    },
  };

  const windows = [];
  for (const [type, { mount, unmount }] of Object.entries(kinds)) {
    const elements = state.gridEl.querySelectorAll(`.card[data-type="${type}"]`);
    if (elements.length === 0) continue;
    windows.push(windowContent({ elements, mount, unmount }));
  }
  state.gridWindow = { disconnect: () => windows.forEach((w) => w.disconnect()) };
}
