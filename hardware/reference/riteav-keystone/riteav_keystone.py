"""RiteAV punchdown keystone reference and its enclosure receptacle API.

The jack's source-authored exterior is generated by replica.rs. The reference
uses the wall's outer plane as its origin, positive Y toward the customer's
plug and positive Z upward. The jack sits inboard along negative Y.

The receptacle uses the existing standard-derived aperture, ease, pocket and
capture fields. Their clearances do not establish the received jack's latch
stiffness or a conforming rear-body fit. The companion README separates the
vendor-observed anatomy from estimated dimensions.

The reference STEP and viewer payloads are declared in frozen-asset.json.
Native composition callers read that same exported geometry through build().
"""

